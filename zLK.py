def get_request_session():
    """创建一个带有防断连重试和长连接 Keep-Alive 的 Requests Session"""
    session = requests.Session()
    retries = Retry(total=3, backoff_factor=1, status_forcelist=[500, 502, 503, 504])
    adapter = HTTPAdapter(max_retries=retries)
    session.mount("http://", adapter)
    session.mount("https://", adapter)
    return session

def convert_t2s(text: str, enabled: bool = True) -> str:
    """繁体转简体函数，仅在内存处理，支持 OpenCC 与 zhconv 兼容"""
    if not text or not enabled:
        return text
    if cc_converter == "zhconv":
        try:
            import zhconv
            return zhconv.convert(text, 'zh-cn')
        except Exception:
            return text
    elif cc_converter:
        try:
            return cc_converter.convert(text)
        except Exception:
            return text
    return text

def sanitize_filename(name: str) -> str:
    """清理非法文件名字符"""
    return re.sub(r'[\\/*?:"<>|]', "_", name)

def get_url_hash(url: str) -> str:
    """获取 URL 的 MD5 哈希作为图片本地唯一标识"""
    return hashlib.md5(url.encode("utf-8")).hexdigest()

